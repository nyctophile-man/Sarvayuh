/**
 * App translations.
 *
 * Every user-facing string in the app lives here. `en` is the source of truth and
 * `hi` holds the Hindi version of each key. Keys are namespaced by screen:
 *
 *   common.*   shared labels (cancel, save, loading …)
 *   home.*     home dashboard, feature sheets (SOS / hospitals / family / feedback)
 *   profile.*  profile screen
 *   records.*  health records screen
 *   alarm.*    medicine alarm screen
 *   ai.*       AI assistant screen
 *   medcard.*  MEDCARD tab + the physical card faces
 *   auth.*     login / signup / forgot / reset / terms / onboarding / profile setup
 *
 * `t('key')` falls back to English and then to the key itself, so a missing
 * translation can never break a screen.
 */

